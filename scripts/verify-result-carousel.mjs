import { chromium } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { server } from './serve.mjs';
await new Promise(resolve=>server.listen(4325,'127.0.0.1',resolve));
const browser=await chromium.launch({channel:'chrome',headless:true});
const report={widths:[],map:'',interactions:[],accessibility:[]};
try{
  const context=await browser.newContext({bypassCSP:true});
  const page=await context.newPage();
  await page.goto('http://127.0.0.1:4325/',{waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('.map-panel iframe').count(),1);
  assert.equal(await page.locator('.map-panel iframe').getAttribute('loading'),'eager');
  assert.equal(await page.locator('[data-load-map]').count(),0);
  report.map='Google iframe is present in initial HTML; no click required';
  await page.locator('img').evaluateAll(imgs=>Promise.all(imgs.map(img=>{img.loading='eager';return img.decode()})));
  await page.addStyleTag({content:'.site-header,.skip-link{visibility:hidden!important}'});
  const host=page.locator('[data-result-carousel]');
  await host.scrollIntoViewIfNeeded();
  await page.locator('[data-result-pause]').click();
  for(const width of [320,390,430,768,1024,1440,1920]){
    await page.setViewportSize({width,height:900});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    const central=page.locator('[data-position="center"]');
    const image=central.locator('img');
    assert.equal(await image.evaluate(el=>getComputedStyle(el).objectFit),'contain');
    const box=await central.boundingBox(),stage=await page.locator('.result-stage').boundingBox();
    assert(box.height<=stage.height,'Card fits inside stage at '+width);
    assert(box.x>=stage.x && box.x+box.width<=stage.x+stage.width,'Central card entirely visible at '+width);
    report.widths.push(width);
    if([390,1440].includes(width))await page.locator('#antes-e-depois').screenshot({path:`artifacts/carrossel-resultados-${width}.png`});
  }
  await page.setViewportSize({width:390,height:900});
  await page.locator('[data-result-direction="1"]').click();
  assert.equal(await page.locator('[data-result-count]').textContent(),'3 / 3');
  await page.locator('[data-result-direction="1"]').click();
  assert.equal(await page.locator('[data-result-count]').textContent(),'1 / 3');
  await page.locator('.result-stage').focus();await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('[data-result-count]').textContent(),'3 / 3');
  assert.equal(await page.locator('[data-result-slide][aria-hidden="true"]').count(),2);
  await page.locator('[data-position="center"] [data-gallery-src]').click();
  assert(await page.locator('#gallery-dialog').isVisible());
  await page.locator('#gallery-dialog img').evaluate(img=>img.decode());
  await page.keyboard.press('Escape');assert(!(await page.locator('#gallery-dialog').isVisible()));
  report.interactions.push('Arrows, wrapping, keyboard, inactive slides inert, image enlargement and Escape');
  await page.locator('[data-result-pause]').click();
  await page.evaluate(()=>document.activeElement?.blur());await page.mouse.move(0,0);
  const before=await page.locator('[data-result-count]').textContent();
  await page.waitForFunction(value=>document.querySelector('[data-result-count]').textContent!==value,before,{timeout:6500});
  await page.locator('[data-result-pause]').click();
  const beforeSwipe=await page.locator('[data-result-count]').textContent();
  await page.locator('.result-stage').dispatchEvent('pointerdown',{clientX:250,clientY:200});
  await page.locator('.result-stage').dispatchEvent('pointerup',{clientX:100,clientY:200});
  assert.notEqual(await page.locator('[data-result-count]').textContent(),beforeSwipe);
  report.interactions.push('Autoplay advances after four seconds; horizontal swipe navigates');
  // Automatic movement stops for reduced motion; manual navigation remains available.
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('[data-result-pause]').isVisible(),false);
  assert.equal(await page.locator('[data-position="center"]').evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
  const axe=await new AxeBuilder({page}).include('#antes-e-depois').include('#localizacao').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  report.accessibility=axe.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}));assert.deepEqual(report.accessibility,[]);
  const nojs=await browser.newContext({javaScriptEnabled:false});const np=await nojs.newPage();
  await np.goto('http://127.0.0.1:4325/',{waitUntil:'domcontentloaded'});
  assert.equal(await np.locator('[data-result-slide]').count(),3);assert.equal(await np.locator('iframe').count(),1);
  for(const card of await np.locator('[data-result-slide]').all())assert(await card.isVisible());
  report.interactions.push('Reduced motion supported; all three photos and map available without JavaScript');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#localizacao').screenshot({path:'artifacts/mapa-automatico-1440.png'});
  await nojs.close();
  await writeFile('artifacts/result-carousel-verification.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
}finally{await browser.close();server.close();}
